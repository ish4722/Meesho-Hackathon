M = {c: col_of(market, c) for c in market.columns}

def wrange(c):
    return f"Weekly_Panel!${W[c]}$2:${W[c]}${nW}"

def prange(c):
    return f"Products!${P[c]}$2:${P[c]}${nP}"

def mrange(c):
    return f"Market_Weekly!${M[c]}$2:${M[c]}${nM}"

