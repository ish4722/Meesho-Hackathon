def write_df(ws, df, hidden_prefix="hidden_", fmt=None, widths=None):
    fmt = fmt or {}
    for j, col in enumerate(df.columns, start=1):
        c = ws.cell(row=1, column=j, value=col)
        c.font = HEAD
        c.fill = FILL_HIDDEN if col.startswith(hidden_prefix) else FILL_HEAD
        c.alignment = Alignment(wrap_text=True, vertical="center")
    for i, row in enumerate(df.itertuples(index=False), start=2):
        for j, v in enumerate(row, start=1):
            if pd.isna(v):
                v = None
            elif hasattr(v, "to_pydatetime"):
                v = v.to_pydatetime()
            c = ws.cell(row=i, column=j, value=v)
            c.font = BASE
            col = df.columns[j - 1]
            if col in fmt:
                c.number_format = fmt[col]
    ws.freeze_panes = "B2"
    for j, col in enumerate(df.columns, start=1):
        ws.column_dimensions[get_column_letter(j)].width = (widths or {}).get(col, max(10, min(26, len(col) + 2)))
    ws.row_dimensions[1].height = 30


