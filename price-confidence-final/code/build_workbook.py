"""
Price Confidence - Excel copy of the synthetic dataset (v2), with a data dictionary built from schema.py and
formula-driven checks. Optional; the pipeline itself only needs the CSVs.

  python build_workbook.py [--data .] [--out ../Price_Confidence_Synthetic_Dataset.xlsx]

THE DATA IS SYNTHETIC: generated by generate_dataset.py from assumed buyer behaviour. It is not Meesho data.
"""
import argparse
import json
import os

import pandas as pd
from openpyxl import Workbook
from openpyxl.comments import Comment
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

import schema

F = "Arial"
BASE, BOLD, TITLE = Font(name=F, size=10), Font(name=F, size=10, bold=True), Font(name=F, size=14, bold=True)
HEAD = Font(name=F, size=10, bold=True, color="FFFFFF")
NOTE = Font(name=F, size=9, italic=True, color="666666")
FILL = {"observable": PatternFill("solid", start_color="4B1248"), "never": PatternFill("solid", start_color="8C8C8C"),
        "future": PatternFill("solid", start_color="A35A00"), "section": PatternFill("solid", start_color="EFE6F0")}
SHEETS = [("Products", "products"), ("Weekly_Panel", "weekly_panel"), ("Market_Weekly", "market_weekly"), ("Reviews", "reviews")]
USE = {
    "id": "Identifier, never a feature", "key": "Join key", "meta": "Text / label, not a feature",
    "observed_static": "Feature (known at launch)", "decision": "Feature (same week: the seller's own choice)",
    "calendar": "Feature (same week: known in advance)", "condition": "Feature only from earlier weeks; offset in its own week",
    "market": "Feature only from earlier weeks", "outcome": "Target; feature only from earlier weeks",
    "state_after": "Feature only from earlier weeks", "future_derived": "NEVER a feature (summarises the future)",
    "seller_private": "NEVER a feature (seller-private; the seller types it into the app)",
    "accounting": "NEVER a feature (uses seller-private costs; evaluation only)", "latent": "NEVER a feature (generator only)",
}


def fill_for(role):
    if role in ("latent", "seller_private", "accounting"):
        return FILL["never"]
    if role == "future_derived":
        return FILL["future"]
    return FILL["observable"]


def write_df(ws, df, table):
    for j, col in enumerate(df.columns, start=1):
        c = ws.cell(row=1, column=j, value=col)
        role = schema.TABLES[table][col][0]
        c.font, c.fill = HEAD, fill_for(role)
        c.alignment = Alignment(wrap_text=True, vertical="center")
        c.comment = Comment(f"{role}: {schema.TABLES[table][col][1]}", "schema.py")
        ws.column_dimensions[get_column_letter(j)].width = max(10, min(28, len(col) + 2))
    for i, row in enumerate(df.itertuples(index=False), start=2):
        for j, v in enumerate(row, start=1):
            if isinstance(v, float) and pd.isna(v):
                continue
            ws.cell(row=i, column=j, value=v.item() if hasattr(v, "item") else v).font = BASE
    ws.freeze_panes = "B2"
    ws.row_dimensions[1].height = 30


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=".")
    ap.add_argument("--out", default=os.path.join("..", "Price_Confidence_Synthetic_Dataset.xlsx"))
    a = ap.parse_args(argv)
    rd = lambda n: pd.read_csv(os.path.join(a.data, n))
    T = {"products": rd("products.csv"), "weekly_panel": rd("weekly_panel.csv"), "market_weekly": rd("market_weekly.csv"),
         "reviews": rd("reviews.csv")}
    man = json.load(open(os.path.join(a.data, "dataset_manifest.json")))
    dq_path = os.path.join(a.data, "reports", "data_quality.json")
    dq = json.load(open(dq_path)) if os.path.exists(dq_path) else None

    wb = Workbook()
    ws = wb.active
    ws.title = "README"
    lines = [
        ("Price Confidence - synthetic listing dataset (v2)", TITLE),
        ("Team Edge Case, IIT Roorkee - Meesho DICE Challenge S3", BASE), ("", BASE),
        ("THIS DATA IS SYNTHETIC. " + man["provenance"], BOLD),
        ("It demonstrates the pricing method. It is not evidence about real Meesho buyers or sellers, and good model scores on it "
         "are not evidence of real-world accuracy.", BOLD), ("", BASE),
        (f"Generator {man['generator_version']}, schema {man['schema_version']}, seed {man['seed']}, scenario '{man['scenario']}'. "
         f"Configuration SHA-256 {man['config_sha256'][:16]}... Python {man['environment']['python']}, numpy {man['environment']['numpy']}, "
         f"pandas {man['environment']['pandas']}.", BASE),
        (f"Rows: {man['rows']}. Listings by category: {man['products_by_category']}. Weeks {man['weeks']['first']} to {man['weeks']['last']}.", BASE),
        ("", BASE), ("Sheets", BOLD),
        ("Products: one row per listing. Weekly_Panel: one row per listing per live week, impressions to reviews. Market_Weekly: "
         "competitor price band and demand per subcategory and week. Reviews: one row per review.", BASE),
        ("Quick_Checks: formulas that recompute funnel totals and rates from the data sheets. Data_Quality: results of data_quality.py. "
         "Data_Dictionary: every column with its role from schema.py and whether a model may use it.", BASE), ("", BASE),
        ("Header colours", BOLD),
        ("Purple = observable to a marketplace (feature use still follows the temporal rule in the dictionary). Orange = summarises the "
         "future (never a feature). Grey = seller-private costs, accounting with those costs, or generator-only truth (hidden_*): "
         "evaluation only, never a model input. Hover a header for its role and meaning.", BASE), ("", BASE),
        ("Economic assumptions (assumptions.json; team assumptions, not Meesho's fees or policies)", BOLD),
    ]
    A = man["config"]["assumptions"]
    for k, v in A.items():
        if k != "notes":
            lines.append((f"{k}: {v}", BASE))
    for i, (t, f) in enumerate(lines, start=1):
        c = ws.cell(row=i, column=1, value=t)
        c.font, c.alignment = f, Alignment(wrap_text=True, vertical="top")
    ws.column_dimensions["A"].width = 140

    for name, table in SHEETS:
        write_df(wb.create_sheet(name), T[table], table)

    # ---------------- Quick_Checks: formulas over the data sheets
    W = T["weekly_panel"]
    col = {c: get_column_letter(i + 1) for i, c in enumerate(W.columns)}
    n = len(W) + 1
    rng = lambda c: f"Weekly_Panel!${col[c]}$2:${col[c]}${n}"
    q = wb.create_sheet("Quick_Checks", 1)
    q["A1"], q["A1"].font = "Funnel totals and rates by category (formulas over Weekly_Panel)", TITLE
    q["A2"], q["A2"].font = "Every number below is a SUMIFS / ratio over the data sheet, so it updates if the data changes.", NOTE
    hdr = ["Category", "Listing-weeks", "Impressions", "Orders placed", "Cancelled", "Dispatched", "RTO", "Delivered", "Returns", "Kept",
           "Orders / 1,000 impr.", "Cancel rate", "RTO rate", "Return rate", "Kept / placed", "Funnel adds up?"]
    for j, h in enumerate(hdr, start=1):
        c = q.cell(row=4, column=j, value=h)
        c.font, c.fill, c.alignment = HEAD, FILL["observable"], Alignment(wrap_text=True)
        q.column_dimensions[get_column_letter(j)].width = 14
    cats = sorted(W.category.unique())
    sums = ["impressions", "orders_placed", "cancelled_orders", "dispatched_orders", "rto_orders", "delivered_orders", "customer_returns", "kept_orders"]
    for i, cat in enumerate(cats + ["All"], start=5):
        q.cell(row=i, column=1, value=cat).font = BOLD
        crit = f'{rng("category")},$A{i}'
        if cat == "All":
            q.cell(row=i, column=2, value=f"=SUM(B5:B{i - 1})")
            for j in range(len(sums)):
                L = get_column_letter(3 + j)
                q.cell(row=i, column=3 + j, value=f"=SUM({L}5:{L}{i - 1})")
        else:
            q.cell(row=i, column=2, value=f"=COUNTIFS({crit})")
            for j, s in enumerate(sums):
                q.cell(row=i, column=3 + j, value=f"=SUMIFS({rng(s)},{crit})")
        q.cell(row=i, column=11, value=f"=IFERROR(D{i}/C{i}*1000,0)").number_format = "0.0"
        q.cell(row=i, column=12, value=f"=IFERROR(E{i}/D{i},0)").number_format = "0.0%"
        q.cell(row=i, column=13, value=f"=IFERROR(G{i}/F{i},0)").number_format = "0.0%"
        q.cell(row=i, column=14, value=f"=IFERROR(I{i}/H{i},0)").number_format = "0.0%"
        q.cell(row=i, column=15, value=f"=IFERROR(J{i}/D{i},0)").number_format = "0.0%"
        q.cell(row=i, column=16, value=f'=IF(AND(D{i}=E{i}+F{i},F{i}=G{i}+H{i},H{i}=I{i}+J{i}),"yes","NO")')
        for j in range(2, 11):
            q.cell(row=i, column=j).number_format = "#,##0"
        for j in range(1, 17):
            if q.cell(row=i, column=j).font != BOLD:
                q.cell(row=i, column=j).font = BASE
    r0 = 6 + len(cats) + 1
    q.cell(row=r0, column=1, value="Listings by category and price-response archetype (archetype is generator-only: evaluation use only)").font = BOLD
    P = T["products"]
    pc = {c: get_column_letter(i + 1) for i, c in enumerate(P.columns)}
    pn = len(P) + 1
    prng = lambda c: f"Products!${pc[c]}$2:${pc[c]}${pn}"
    archs = sorted(P.hidden_archetype.unique())
    q.cell(row=r0 + 1, column=1, value="Category").font = HEAD
    q.cell(row=r0 + 1, column=1).fill = FILL["observable"]
    for j, ar in enumerate(archs, start=2):
        c = q.cell(row=r0 + 1, column=j, value=ar)
        c.font, c.fill, c.alignment = HEAD, FILL["never"], Alignment(wrap_text=True)
    for i, cat in enumerate(cats, start=r0 + 2):
        q.cell(row=i, column=1, value=cat).font = BOLD
        for j in range(2, 2 + len(archs)):
            hc = f"{get_column_letter(j)}${r0 + 1}"
            q.cell(row=i, column=j, value=f'=COUNTIFS({prng("category")},$A{i},{prng("hidden_archetype")},{hc})').font = BASE

    # ---------------- Data_Quality
    d = wb.create_sheet("Data_Quality", 2)
    d["A1"], d["A1"].font = "data_quality.py results", TITLE
    if dq:
        for j, h in enumerate(["Check", "Level", "Status", "Detail"], start=1):
            c = d.cell(row=3, column=j, value=h)
            c.font, c.fill = HEAD, FILL["observable"]
        for i, chk in enumerate(dq["checks"], start=4):
            for j, k in enumerate(["check", "level", "status", "detail"], start=1):
                c = d.cell(row=i, column=j, value=str(chk[k]))
                c.font, c.alignment = (BOLD if k == "status" and chk[k] != "PASS" else BASE), Alignment(wrap_text=True, vertical="top")
        d.column_dimensions["A"].width, d.column_dimensions["D"].width = 42, 110
    else:
        d["A3"] = "Run python data_quality.py first."

    # ---------------- Data_Dictionary from schema.py
    dd = wb.create_sheet("Data_Dictionary", 3)
    for j, h in enumerate(["Sheet", "Column", "Role", "Meaning", "May a model use it?"], start=1):
        c = dd.cell(row=1, column=j, value=h)
        c.font, c.fill = HEAD, FILL["observable"]
    i = 2
    for name, table in SHEETS:
        for colname, (role, desc) in schema.TABLES[table].items():
            for j, v in enumerate([name, colname, role, desc, USE[role]], start=1):
                c = dd.cell(row=i, column=j, value=v)
                c.font, c.alignment = BASE, Alignment(wrap_text=True, vertical="top")
            i += 1
    for L, wdt in zip("ABCDE", [16, 34, 16, 80, 46]):
        dd.column_dimensions[L].width = wdt
    dd.freeze_panes = "A2"

    wb.save(a.out)
    print(a.out, "written")


if __name__ == "__main__":
    main()
